/**
 * Makes sigstore-java reachable in the native image: every class it ships, plus the few outside it
 * that its plumbing instantiates by name.
 *
 * <p>The library resolves things reflectively at four different depths, and each one only shows up
 * once the run gets that far. Protobuf messages are built through {@code newBuilder} and read
 * through a {@code FieldAccessorTable} that looks accessors up by name. The OIDC, Fulcio, Rekor,
 * trust-root and timestamp clients parse JSON into classes whose fields are set the same way. The
 * identity token is a JWT, which google-api-client parses by calling a no-argument constructor it
 * finds reflectively. And gRPC picks its transport, name resolver and load balancer through
 * {@code ServiceLoader} — so those service files ship as resources (see application.properties) and
 * <em>every</em> class they name is registered here, including the server provider nothing uses:
 * shipping the file and registering only part of it is worse than not shipping it, since
 * ServiceLoader then reads a name it cannot load and the binary dies on startup.
 *
 * <p>Listing the whole jar rather than the packages known to bite is deliberate. Each narrower
 * attempt — the proto package, then the client packages — compiled, passed every test on the JVM,
 * and failed one step further into the first real signature. The cost of being broad here is image
 * size; the cost of being precise was a round trip through CI per package.
 *
 * <p>Regenerate the list with:
 *
 * <pre>
 * unzip -l ~/.m2/repository/dev/sigstore/sigstore-java/&lt;version&gt;/sigstore-java-&lt;version&gt;.jar \
 *   | awk '/\.class$/ {print $4}' | sed 's|/|.|g;s|\.class$||' | sort
 * </pre>
 */
