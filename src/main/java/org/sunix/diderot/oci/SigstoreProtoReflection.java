import io.quarkus.runtime.annotations.RegisterForReflection;

/**
 * Makes sigstore's protobuf classes reachable in the native image.
 *
 * <p>The trust root arrives as JSON and is parsed into protobuf messages. protobuf's
 * {@code FieldAccessorTable} resolves a message's getters and setters <em>by name, through
 * reflection</em>, so native-image's analysis cannot see them: the classes are compiled in, the
 * accessors are not, and the binary fails at the first signature with "Could not parse trusted
 * root" — while the JVM build works perfectly. The well-known types are here for the same reason:
 * a trust root carries {@code google.protobuf.Timestamp} validity windows.
 *
 * <p>The same applies one layer up: the OIDC, Fulcio, Rekor, trust-root and timestamp clients
 * parse their JSON responses into classes whose fields are read reflectively, and a native image
 * that has not been told about them fails with an empty message — the first signed publish said
 * only "Could not build a sigstore signer:" and nothing more.
 *
 * <p>And one layer up again: the identity token is a JWT, which google-api-client parses by
 * instantiating its own classes through a no-argument constructor — "unable to create new instance
 * of class JsonWebSignature$Header because it has no accessible default constructor", a message
 * that only appears once there is a real token to parse, which is to say only in CI with
 * `id-token: write`.
 *
 * <p>The gRPC entries are the same problem through a third door: a client finds its transport,
 * name resolver and load balancer through ServiceLoader, so the service files have to ship as
 * resources and the classes they name have to be instantiable.
 *
 * <p>Regenerate the list with:
 *
 * <pre>
 * unzip -l ~/.m2/repository/dev/sigstore/sigstore-java/&lt;version&gt;/sigstore-java-&lt;version&gt;.jar \
 *   | awk '/dev\/sigstore\/proto.*\.class$/ {print $4}' | sed 's|/|.|g;s|\.class$||' | sort
 * </pre>
 */
